"""
report.py - PDF report generation with ReportLab (returns bytes, no temp files).
"""
from __future__ import annotations

import io
from datetime import date, datetime
from xml.sax.saxutils import escape

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from face_engine import Student

NAVY = colors.HexColor("#14325c")
LIGHT = colors.HexColor("#eef3fa")
RED = colors.HexColor("#b3261e")
RED_LIGHT = colors.HexColor("#fdecea")


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawString(doc.leftMargin, 1.0 * cm, "Generated by AI Attendance Agent")
    canvas.drawRightString(A4[0] - doc.rightMargin, 1.0 * cm, f"Page {doc.page}")
    canvas.restoreState()


def _table(data, col_widths, header_color, zebra):
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), header_color),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, zebra]),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b8c2d0")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return t


def build_pdf_report(institute: str, subtitle: str, report_date: date,
                     present_df: pd.DataFrame, absent: list[Student],
                     total_enrolled: int, generated_at: datetime) -> bytes:
    """Build the attendance PDF and return it as bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=1.8 * cm, rightMargin=1.8 * cm,
                            topMargin=1.6 * cm, bottomMargin=1.8 * cm,
                            title=f"Attendance Report {report_date:%Y-%m-%d}",
                            author="AI Attendance Agent")
    ss = getSampleStyleSheet()
    h_inst = ParagraphStyle("inst", parent=ss["Title"], fontSize=20, textColor=NAVY,
                            alignment=TA_CENTER, spaceAfter=2)
    h_sub = ParagraphStyle("sub", parent=ss["Normal"], fontSize=12, alignment=TA_CENTER,
                           textColor=colors.HexColor("#444444"))
    h_meta = ParagraphStyle("meta", parent=ss["Normal"], fontSize=10, alignment=TA_CENTER,
                            textColor=colors.HexColor("#555555"), leading=14)
    h_sec = ParagraphStyle("sec", parent=ss["Heading2"], textColor=NAVY, spaceBefore=14, spaceAfter=6)
    h_sec_red = ParagraphStyle("secr", parent=h_sec, textColor=RED)
    cell = ParagraphStyle("cell", parent=ss["Normal"], fontSize=9, leading=11)
    note = ParagraphStyle("note", parent=ss["Italic"], fontSize=9, textColor=colors.grey)

    total_present = len(present_df)
    total_absent = len(absent)
    pct = (total_present / total_enrolled * 100) if total_enrolled else 0.0

    story = [
        Paragraph(escape(institute), h_inst),
        Paragraph(escape(subtitle), h_sub),
        Spacer(1, 4),
        Paragraph(f"<b>Date of Report:</b> {report_date:%A, %d %B %Y}<br/>"
                  f"<b>Generated:</b> {generated_at:%Y-%m-%d %H:%M}", h_meta),
        Spacer(1, 12),
    ]

    # ---- Summary ---------------------------------------------------------- #
    summary = Table(
        [["Total Enrolled", "Total Present", "Total Absent", "Attendance %"],
         [str(total_enrolled), str(total_present), str(total_absent), f"{pct:.1f}%"]],
        colWidths=[4.35 * cm] * 4)
    summary.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 1), (-1, 1), LIGHT),
        ("TEXTCOLOR", (2, 1), (2, 1), RED),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, 1), (-1, 1), "Helvetica-Bold"), ("FONTSIZE", (0, 1), (-1, 1), 16),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.white),
    ]))
    story += [summary]

    # ---- Present table ---------------------------------------------------- #
    story.append(Paragraph("Present Students", h_sec))
    if present_df.empty:
        story.append(Paragraph("No student has been marked present on this date.", note))
    else:
        rows = [["Roll No", "Name", "Date", "Time", "Status"]]
        for r in present_df.itertuples(index=False):
            rows.append([r[2], Paragraph(escape(r[3]), cell), r[0], r[1], r[4]])
        story.append(_table(rows, [2.4 * cm, 6.2 * cm, 3.0 * cm, 2.8 * cm, 3.0 * cm], NAVY, LIGHT))

    # ---- Absent table ----------------------------------------------------- #
    story.append(Paragraph("Absent Students", h_sec_red))
    if not absent:
        story.append(Paragraph("No absentees - full attendance.", note))
    else:
        rows = [["Roll No", "Name", "Date", "Status"]]
        for s in absent:
            rows.append([s.roll, Paragraph(escape(s.name), cell), f"{report_date:%Y-%m-%d}", "ABSENT"])
        t = _table(rows, [2.4 * cm, 8.6 * cm, 3.4 * cm, 3.0 * cm], RED, RED_LIGHT)
        t.setStyle(TableStyle([("TEXTCOLOR", (3, 1), (3, -1), RED),
                               ("FONTNAME", (3, 1), (3, -1), "Helvetica-Bold")]))
        story.append(t)

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
